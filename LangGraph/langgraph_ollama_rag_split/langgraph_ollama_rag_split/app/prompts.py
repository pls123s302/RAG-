def build_route_prompt(question: str) -> str:
    """
    构建路由判断 Prompt。

    RAG：需要查知识库 / 图谱 / 文档
    DIRECT：普通闲聊或常识问题
    """

    return f"""
你是一个路由判断器。

你的任务是判断用户问题是否需要查询本地知识库。

如果问题涉及：
1. 小说、文档、知识库中的具体内容；
2. 专有名词；
3. 人物关系、实体关系、设定关系；
4. 需要根据已有资料回答；
5. 可能需要检索上下文；
则回答：RAG

如果问题是普通闲聊、简单常识、代码解释、无需知识库的问题，则回答：DIRECT

只允许输出 RAG 或 DIRECT，不要输出其他内容。

用户问题：
{question}
"""


def build_rag_answer_prompt(question: str, context: str) -> str:
    """
    构建 RAG 回答 Prompt。

    context 里可能包含：
    1. 原始文档片段；
    2. Neo4j 知识图谱关系。
    """

    return f"""
你是一个基于本地知识库回答问题的助手。

你会收到两类可能的检索资料：

1. 【原始文档片段】
   - 来自 Chroma 向量库；
   - 通常包含原文内容、章节、来源等信息；
   - 适合用来回答细节、剧情、定义、原文依据类问题。

2. 【知识图谱资料】
   - 来自 Neo4j；
   - 通常是实体之间的结构化关系；
   - 适合用来回答人物关系、设定关系、实体关联、多跳关系类问题。

回答要求：
1. 必须优先依据检索资料回答。
2. 如果原始文档片段和知识图谱资料都相关，请综合二者回答。
3. 如果两类资料有冲突，优先相信原始文档片段，并说明存在不一致。
4. 如果资料不足，请明确说：“知识库中没有找到足够信息”。
5. 不要编造知识库中没有的信息。
6. 回答要自然、清晰，尽量用中文。
7. 如果能看出依据来自知识图谱关系，可以适当说明实体之间的关系。
8. 如果能看出依据来自原始文档，可以适当引用来源信息。

检索资料：
{context}

用户问题：
{question}

请给出回答：
"""


def build_direct_answer_prompt(question: str) -> str:
    """
    构建直接回答 Prompt。

    不使用知识库，直接回答用户问题。
    """

    return f"""
请直接回答用户问题，不需要调用知识库。

要求：
1. 用中文回答。
2. 回答要简洁清楚。
3. 如果不确定，请说明不确定，不要编造。

用户问题：
{question}
"""